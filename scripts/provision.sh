#!/usr/bin/env bash
# Provision a fresh Ubuntu server for this app. Run as root, immediately after the first
# SSH login, from inside a clone of this repository:
#
#   git clone --branch main <repo-url> ~/<app-name> && cd ~/<app-name>
#   # staging is the default branch, so production names main
#   bash scripts/provision.sh <domain>
#
# <domain> is the public hostname the app will be served at (DNS may still be
# propagating; certbot-setup.sh verifies it later). APP_NAME defaults to the clone
# directory's basename and names the Compose project, the nginx site, the systemd units,
# and the /var/log and /var/backups directories. Override it with APP_NAME=<name> in
# the environment. The generated .env lands in the clone and is never overwritten.
#
# Next steps, in order:
#   bash scripts/certbot-setup.sh --email <addr>   # first certificate (after DNS)
#   bash scripts/deploy.sh                          # first deploy (or: npm run deploy)
#   bash scripts/install-backup.sh                  # off-site copies, after SPACES_*
set -euo pipefail

DOMAIN="${1:?usage: bash scripts/provision.sh <domain>}"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(dirname "$SCRIPT_DIR")"
APP_NAME="${APP_NAME:-$(basename "$REPO_DIR")}"

echo "==> Provisioning '$APP_NAME' for https://$DOMAIN (clone: $REPO_DIR)"

echo "==> Updating system packages..."
sudo apt-get update -qq
sudo apt-get upgrade -y -qq

echo "==> Installing required packages..."
# dnsutils provides dig, which certbot-setup.sh uses to confirm DNS before issuance.
sudo apt-get install -y -qq \
  ca-certificates curl git vim dnsutils certbot python3-certbot-nginx

echo "==> Adding Docker apt repository..."
sudo install -m 0755 -d /etc/apt/keyrings
sudo curl -fsSL https://download.docker.com/linux/ubuntu/gpg \
  -o /etc/apt/keyrings/docker.asc
sudo chmod a+r /etc/apt/keyrings/docker.asc

# shellcheck source=/dev/null
UBUNTU_CODENAME="$(. /etc/os-release && echo "$VERSION_CODENAME")"
echo \
  "deb [arch=$(dpkg --print-architecture) \
  signed-by=/etc/apt/keyrings/docker.asc] \
  https://download.docker.com/linux/ubuntu \
  $UBUNTU_CODENAME stable" | \
  sudo tee /etc/apt/sources.list.d/docker.list > /dev/null

echo "==> Installing Docker..."
sudo apt-get update -qq
sudo apt-get install -y docker-ce docker-ce-cli containerd.io \
  docker-buildx-plugin docker-compose-plugin --fix-missing

sudo usermod -aG docker "${USER:-$(id -un)}"

echo "==> Configuring host nginx..."
# nginx is already installed as a dependency of python3-certbot-nginx above.
# Remove the default site so nginx doesn't claim ports 80/443 before we configure it.
sudo rm -f /etc/nginx/sites-enabled/default
sudo systemctl enable nginx
sudo systemctl start nginx

echo "==> Generating .env file..."
if [ -f "$REPO_DIR/.env" ]; then
  echo "    .env already exists — skipping."
else
  PG_PASS=$(openssl rand -hex 16)
  SECRET=$(openssl rand -hex 32)
  ADMIN_PASS=$(openssl rand -hex 16)
  umask 077  # .env holds secrets; create it mode 600
  cat > "$REPO_DIR/.env" << ENV
# Generated by scripts/provision.sh on $(date -u +%F). Secrets live only in this file.

# --- Identity -------------------------------------------------------------------
# APP_NAME names the clone under \$HOME, the nginx site, the log and backup
# directories, and the systemd units. COMPOSE_PROJECT_NAME pins the data volumes
# (<name>_postgres_data, <name>_uploads_data); changing it orphans all data.
APP_NAME=$APP_NAME
DOMAIN=$DOMAIN
COMPOSE_PROJECT_NAME=$APP_NAME

# --- Environment and branch (scripts/deploy.sh) ---------------------------------
# Production serves the main branch; deploy.sh refuses a clone on any other branch.
APP_ENVIRONMENT=production
DEPLOY_BRANCH=main

# --- PostgreSQL (db service) and the URL Flask uses to reach it -----------------
POSTGRES_USER=app
POSTGRES_PASSWORD=$PG_PASS
POSTGRES_DB=app
DATABASE_URL=postgresql://app:$PG_PASS@db:5432/app

# --- Flask ----------------------------------------------------------------------
SECRET_KEY=$SECRET
FLASK_ENV=production
CORS_ALLOWED_ORIGINS=https://$DOMAIN
# OAuth redirect URIs and the WebAuthn origin are built from PUBLIC_BASE_URL.
PUBLIC_BASE_URL=https://$DOMAIN
WEBAUTHN_RP_NAME=$APP_NAME
SESSION_COOKIE_SECURE=true
SESSION_COOKIE_SAMESITE=Strict
GUNICORN_WORKERS=4

# --- First admin (src_back/seed.py) ---------------------------------------------
# Fill in ADMIN_EMAIL before the first deploy. The seed then creates that admin with
# this password and never changes the account afterwards.
ADMIN_EMAIL=
ADMIN_PASSWORD=$ADMIN_PASS

# --- Outgoing mail (src_back/mailer.py) -----------------------------------------
# A blank SMTP_HOST keeps mail off. SMTP_SECURITY is starttls (port 587), ssl (465), or
# none; SMTP_FROM defaults to SMTP_USERNAME and must be an email address.
SMTP_HOST=
SMTP_PORT=
SMTP_SECURITY=starttls
SMTP_USERNAME=
SMTP_PASSWORD=
SMTP_FROM=

# --- Loopback ports published by Compose; host nginx proxies to them -------------
BACKEND_PORT=5000
FRONTEND_HOST_PORT=8080

# --- Frontend build arg (the built SPA calls /api/ relative to its own origin) ---
VITE_API_URL=http://backend:5000

# --- Let's Encrypt registration address (scripts/certbot-setup.sh) --------------
CERTBOT_EMAIL=

# --- Operational alerts (scripts/alert.sh) --------------------------------------
# Blank means log-only. Format is text (ntfy.sh), slack, or discord.
ALERT_WEBHOOK_URL=
ALERT_WEBHOOK_FORMAT=text

# --- Backups (scripts/backup.sh) ------------------------------------------------
# Every daily run keeps its newest RETAIN_LOCAL_DAILY dumps and uploads archives in
# /var/backups/$APP_NAME/daily. For off-site copies too, create a bucket and an
# access key, fill in SPACES_*, and run scripts/install-backup.sh.
SPACES_ENDPOINT=https://nyc3.digitaloceanspaces.com
SPACES_REGION=nyc3
SPACES_BUCKET=
SPACES_ACCESS_KEY_ID=
SPACES_SECRET_ACCESS_KEY=
BACKUP_PREFIX=prod
RETAIN_DAILY=14
RETAIN_WEEKLY=8
RETAIN_MONTHLY=6
RETAIN_LOCAL_DAILY=7
ENV
# end of .env heredoc
  echo "    .env created at $REPO_DIR/.env (mode 600)."
  echo "    Fill in CERTBOT_EMAIL, ALERT_WEBHOOK_URL, and SPACES_* before running the"
  echo "    steps that use them."
  echo "    Mail stays off until SMTP_HOST and the other SMTP_* values are filled in."
  echo "    Fill in ADMIN_EMAIL before the first deploy; that admin signs in with the"
  echo "    generated ADMIN_PASSWORD."
fi

echo ""
echo "==> Provisioning complete."
if [ -f /var/run/reboot-required ]; then
  echo "    Kernel was updated — rebooting in 5 seconds."
  echo "    SSH back in after ~30 seconds to continue."
  sleep 5
  sudo reboot
else
  echo "    Log out and back in (or run 'newgrp docker') so the docker group applies."
fi
